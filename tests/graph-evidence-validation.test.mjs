import test from 'node:test';
import assert from 'node:assert/strict';
import {createScientificExperimentGraph} from '../src/experiment-graph.mjs';
import {validateGraphNodeEvidence} from '../src/graph-evidence-validation.mjs';
const spec={claim:'Independent speed conversion example',referenceId:'textbook-kinematics',locator:'section 1',observations:[{expected:10,expectedUnit:'m/s',actual:36,actualUnit:'km/h'}]};
test('independent citation examples never imply graph output validation',()=>{
 const values=[999,999];
 const graph=createScientificExperimentGraph();
 graph.addSource('observations','time-series',values,{metadata:{units:'m/s'}});
 const before=graph.exportJSON();
 const result=validateGraphNodeEvidence(graph,'observations',spec);
 assert.equal(result.citationExamples.status,'reproduced');
 assert.equal(result.citationExamples.scope,'dimension-and-numeric-examples-only');
 assert.equal(result.relationship,'independent-citation-examples');
 assert.equal(result.nodeOutputValidated,false);
 assert.equal(Object.hasOwn(result,'evidence'),false);
 assert.equal(result.citationExamples.referenceId,spec.referenceId);
 assert.equal(result.citationExamples.locator,spec.locator);
 assert.equal(Object.hasOwn(result,'status'),false);
 const unrelated=validateGraphNodeEvidence(graph,'observations',{...spec,observations:[{expected:1,actual:1,expectedUnit:'m/s',actualUnit:'m/s'}]});
 assert.equal(unrelated.citationExamples.status,'reproduced');
 assert.equal(unrelated.nodeOutputValidated,false);
 const contradicted=validateGraphNodeEvidence(graph,'observations',{...spec,observations:[{expected:1,actual:2,expectedUnit:'m/s',actualUnit:'m/s'}]});
 assert.equal(contradicted.citationExamples.status,'contradicted');
 assert.equal(contradicted.nodeOutputValidated,false);
 assert.equal(result.nodeType,'time-series');
 assert.equal(graph.exportJSON(),before);
 values[0]=-17;
 const changed=validateGraphNodeEvidence(graph,'observations',spec);
 assert.equal(changed.nodeOutputValidated,false);
 assert.equal(changed.citationExamples.status,'reproduced');
 assert.equal(Object.hasOwn(changed,'evidence'),false);
 assert.deepEqual(graph.execute('observations').value,[-17,999]);
});
test('rejects unknown graph nodes and dimension mismatches',()=>{
 const graph=createScientificExperimentGraph();graph.addSource('x','time-series',[1,2]);
 assert.throws(()=>validateGraphNodeEvidence(graph,'missing',spec),/Unknown experiment node/);
 assert.throws(()=>validateGraphNodeEvidence(graph,'x',{...spec,observations:[{expected:1,expectedUnit:'m',actual:1,actualUnit:'s'}]}),/Incompatible/);
});
